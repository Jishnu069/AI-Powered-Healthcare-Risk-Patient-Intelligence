import mlflow
import joblib
import pandas as pd
from pathlib import Path

PROJECT_ROOT = Path(
    r"C:\Users\jishn\Desktop\AI-Powered Healthcare Risk & Patient Intelligence"
)

mlflow.set_tracking_uri(
    f"sqlite:///{(PROJECT_ROOT / 'mlflow.db').as_posix()}"
)

# Load the registered model
model = mlflow.sklearn.load_model("models:/BestModel/1")

# Load the saved preprocessor
preprocessor = joblib.load(
    PROJECT_ROOT / "models" / "preprocessor.pkl"
)

# Get the 123 feature names expected by the model
expected_features = list(model.feature_names_in_)

# Get the 256 feature names generated by the preprocessor
preprocessor_features = list(
    preprocessor.get_feature_names_out()
)

print("Model expects:", len(expected_features), "features")
print("Preprocessor produces:", len(preprocessor_features), "features")

print("\n--- Feature comparison ---")

missing_features = [
    feature
    for feature in expected_features
    if feature not in preprocessor_features
]

print("Expected features missing from preprocessor:", len(missing_features))

for feature in missing_features:
    print(feature)

print("\n--- Feature selection diagnosis complete ---")